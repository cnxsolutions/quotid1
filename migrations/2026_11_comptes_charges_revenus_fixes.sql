-- Recentrage du bot : comptes mis à jour à la main (avec écart depuis la dernière fois),
-- charges et revenus fixes purement informatifs.
-- À exécuter dans Supabase > SQL Editor AVANT de relancer le bot.
-- Idempotent : peut être rejoué sans risque.

-- 1. Comptes : mémoriser le solde précédent et la date de la dernière mise à jour.
--    Les comptes existants n'ont pas encore de date : elle se remplit à leur prochaine mise à jour.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS previous_balance numeric(12,2);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS balance_updated_on date;
UPDATE accounts SET balance = COALESCE(initial_balance, 0) WHERE balance IS NULL;

-- 2. Revenus fixes (salaire, etc.) : informatifs, aucun lien avec les comptes.
CREATE TABLE IF NOT EXISTS fixed_incomes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text          NOT NULL UNIQUE,
    amount     numeric(12,2) NOT NULL CHECK (amount > 0),
    frequency  text          NOT NULL CHECK (frequency IN ('Mensuel', 'Annuel')),
    created_at timestamptz   NOT NULL DEFAULT now()
);

-- Le bot se connecte avec la clé anon : mêmes droits que sur les tables existantes.
GRANT SELECT, INSERT, UPDATE, DELETE ON fixed_incomes TO anon;

-- Vérification
SELECT id, name, balance, previous_balance, balance_updated_on FROM accounts ORDER BY name;
