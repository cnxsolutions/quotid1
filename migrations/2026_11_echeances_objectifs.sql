-- Échéances des charges annuelles et objectifs d'épargne.
-- À exécuter dans Supabase > SQL Editor APRÈS 2026_11_point_mensuel.sql,
-- et avant de relancer le bot. Idempotent : peut être rejoué sans risque.

-- 1. Mois d'échéance d'une charge annuelle (1 = janvier … 12 = décembre).
ALTER TABLE charges
    ADD COLUMN IF NOT EXISTS due_month smallint CHECK (due_month BETWEEN 1 AND 12);

-- 2. Relevés : épargne au moment du point (pour mesurer le rythme), charges réellement dues
--    sur la période et provisions pour charges annuelles. Vides pour les relevés plus anciens.
ALTER TABLE checkpoints ADD COLUMN IF NOT EXISTS savings_balance numeric(12,2);
ALTER TABLE checkpoints ADD COLUMN IF NOT EXISTS charges_due numeric(12,2);
ALTER TABLE checkpoints ADD COLUMN IF NOT EXISTS provisions numeric(12,2);

-- 3. Objectifs d'épargne. deadline = 1er jour du mois visé, NULL = sans date (réserve).
CREATE TABLE IF NOT EXISTS savings_goals (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text          NOT NULL UNIQUE,
    amount     numeric(12,2) NOT NULL CHECK (amount > 0),
    deadline   date          CHECK (extract(day FROM deadline) = 1),
    created_at timestamptz   NOT NULL DEFAULT now()
);

-- 4. Nouvelle version de record_checkpoint (deux paramètres de plus) : l'ancienne est supprimée
--    pour éviter deux fonctions homonymes, que PostgREST ne saurait pas départager.
DROP FUNCTION IF EXISTS record_checkpoint(date, date, numeric, numeric, numeric, numeric, jsonb);

CREATE OR REPLACE FUNCTION record_checkpoint(
    p_month          date,
    p_taken_on       date,
    p_income         numeric,
    p_fixed_incomes  numeric,
    p_charges        numeric,
    p_charges_due    numeric,
    p_provisions     numeric,
    p_savings_target numeric,
    p_balances       jsonb
) RETURNS checkpoints
LANGUAGE plpgsql
AS $$
DECLARE
    v_checkpoint checkpoints;
BEGIN
    UPDATE accounts AS a
    SET previous_balance   = a.balance,
        balance            = (b.value ->> 'balance')::numeric,
        balance_updated_on = p_taken_on
    FROM jsonb_array_elements(p_balances) AS b(value)
    WHERE a.id = (b.value ->> 'id')::bigint;

    INSERT INTO checkpoints (
        month, taken_on, total_balance, savings_balance, income, fixed_incomes,
        charges, charges_due, provisions, savings_target
    )
    SELECT p_month, p_taken_on,
           COALESCE(sum(balance), 0),
           COALESCE(sum(balance) FILTER (WHERE kind = 'epargne'), 0),
           p_income, p_fixed_incomes, p_charges, p_charges_due, p_provisions, p_savings_target
    FROM accounts
    ON CONFLICT (month) DO UPDATE
    SET taken_on        = EXCLUDED.taken_on,
        total_balance   = EXCLUDED.total_balance,
        savings_balance = EXCLUDED.savings_balance,
        income          = EXCLUDED.income,
        fixed_incomes   = EXCLUDED.fixed_incomes,
        charges         = EXCLUDED.charges,
        charges_due     = EXCLUDED.charges_due,
        provisions      = EXCLUDED.provisions,
        savings_target  = EXCLUDED.savings_target
    RETURNING * INTO v_checkpoint;

    RETURN v_checkpoint;
END;
$$;

-- Le bot se connecte avec la clé anon : mêmes droits que sur les tables existantes.
GRANT SELECT, INSERT, UPDATE, DELETE ON savings_goals TO anon;
GRANT EXECUTE ON FUNCTION
    record_checkpoint(date, date, numeric, numeric, numeric, numeric, numeric, numeric, jsonb) TO anon;
